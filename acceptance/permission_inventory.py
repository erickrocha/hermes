#!/usr/bin/env python3
"""EPIC-AC-01-S01 groundwork: derive a resource x action permission inventory from the code.

Reads the OpenAPI document of a running API and the endpoint sources, and prints a Markdown table:
one row per operation with its proposed permission (resource.action), the authorization predicate(s)
the handler calls, and the roles the `**Roles:**` statement names. A reviewer collapses the rows into
the catalogue. Stdlib only.   usage: permission_inventory.py [openapi.json] > inventory.md
"""
import glob, json, os, re, sys, urllib.request
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "backend", "application", "src", "endpoints")
ROLES = ["SysAdmin", "TenantOwner", "TenantUser", "Driver", "Mechanic"]
VERBS = {"conclude", "cancel", "checkout", "restore", "unify", "receipt", "sync", "import", "preview", "invite",
         "end", "issue-part", "change-password", "average", "confirm", "reconcile", "pending", "alert", "monitor",
         "queue", "call-list", "cards", "matrix", "active", "extend", "renew", "generate", "stamp", "plan",
         "approve", "order", "receive"}


def spec():
    if len(sys.argv) > 1:
        return json.load(open(sys.argv[1]))
    return json.load(urllib.request.urlopen(os.environ.get("HERMES_API", "http://127.0.0.1:8080") + "/api-docs/openapi.json"))


def predicates():
    """(METHOD, path) -> sorted predicate names called in the handler that follows its #[utoipa::path]."""
    out = {}
    for f in glob.glob(os.path.join(SRC, "*_endpoint.rs")):
        text = open(f).read()
        blocks = [m for m in re.finditer(r"#\[utoipa::path\(\s*(get|post|put|delete)\s*,[^)]*?\bpath\s*=\s*\"([^\"]+)\"", text, re.S)]
        for i, m in enumerate(blocks):
            end = blocks[i + 1].start() if i + 1 < len(blocks) else len(text)
            body = text[m.end():end]
            preds = sorted(set(re.findall(r"\b(can_[a-z_]+|is_unbound_sys_admin|lacks_required_tenant)\b", body)))
            if not preds:   # no predicate in the handler: say how it is guarded instead
                file_preds = sorted(set(re.findall(r"\b(can_[a-z_]+)\(", text)))
                if re.search(r"Role::|\.role\b", body):
                    preds = ["inline role check"]
                elif file_preds and re.search(r"\bfn [a-z_]+\(", body) and any(p in body for p in file_preds):
                    preds = file_preds
                elif re.search(r"tenant_id|current_user", body):
                    preds = ["tenant scope only"]
                else:
                    preds = ["none visible"]
            out[(m.group(1).upper(), m.group(2))] = preds
    return out


def stated(op):
    # only the description that carries the marker, and only up to its end: other responses name roles too
    texts = [r.get("description", "") for r in op["responses"].values() if "**Roles:**" in r.get("description", "")]
    if not texts:
        return "?"
    s = texts[0].split("**Roles:**", 1)[1].split("--")[0]
    if re.search(r"\bany (authenticated role|caller)\b", s):
        return "all"
    return ",".join(r for r in ROLES if re.search(r"\b%s\b" % r, s)) or "?"


def classify(method, path):
    segs = [s for s in path.strip("/").split("/") if s]
    names = [s for s in segs if not s.startswith("{") and s not in ("uuid", "id")]
    has_id = any(s.startswith("{") for s in segs)
    verb = None
    if len(names) > 1 and names[-1] in VERBS:
        verb = names.pop()
    elif len(names) == 1 and names[0] in VERBS:
        verb = None
    resource = ".".join(names)
    if verb:
        action = verb
    elif method == "GET":
        action = "read"
    elif method == "POST":
        action = "create"
    elif method == "PUT":
        action = "update"
    else:
        action = "delete"
    return resource, action


def main():
    d, pred = spec(), predicates()
    rows = []
    for path, ops in d["paths"].items():
        for m, op in ops.items():
            if m not in ("get", "post", "put", "delete"):
                continue
            res, act = classify(m.upper(), path)
            rows.append((res, act, m.upper(), path, ",".join(pred.get((m.upper(), path), [])) or "—", stated(op)))
    rows.sort()
    perms = {}
    for r in rows:
        perms.setdefault(f"{r[0]}.{r[1]}", []).append(r)
    print(f"<!-- generated by acceptance/permission_inventory.py: {len(rows)} operations -> {len(perms)} proposed permissions -->")
    print("| Permission (resource.action) | Operations | Predicate(s) called | Roles named today |\n|---|---|---|---|")
    for p, rs in sorted(perms.items()):
        ops = "<br>".join(f"`{r[2]} {r[3]}`" for r in rs)
        print(f"| `{p}` | {ops} | {' / '.join(sorted({r[4] for r in rs}))} | {' / '.join(sorted({r[5] for r in rs}))} |")


if __name__ == "__main__":
    main()
